// Слияние двух отсортированных массивов in-place.
//
// Идём с конца: сравниваем большие элементы и кладём их в хвост arr1.
// Так мы никогда не затираем ещё не обработанные элементы arr1.
// Время O(m+n), память O(1).
package main

import "fmt"

func merge(arr1 []int, m int, arr2 []int, n int) {
	i, j, k := m-1, n-1, m+n-1

	// Пока есть элементы в arr2 — выбираем больший из хвостов.
	// Если arr2 закончился раньше, остаток arr1 уже стоит на месте.
	for j >= 0 {
		if i >= 0 && arr1[i] > arr2[j] {
			arr1[k] = arr1[i]
			i--
		} else {
			arr1[k] = arr2[j]
			j--
		}
		k--
	}
}

func main() {
	a1 := []int{1, 3, 5, 7, 0, 0, 0, 0}
	merge(a1, 4, []int{2, 4, 6, 8}, 4)
	fmt.Println(a1) // [1 2 3 4 5 6 7 8]

	a2 := []int{1, 2, 3, 0, 0, 0}
	merge(a2, 3, []int{2, 5, 6}, 3)
	fmt.Println(a2) // [1 2 2 3 5 6]

	a3 := []int{0}
	merge(a3, 0, []int{1}, 1)
	fmt.Println(a3) // [1]
}
