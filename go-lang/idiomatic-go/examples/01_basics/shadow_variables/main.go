// Классическое затенение: `x := 5` внутри блока создает новую переменную,
// внешняя x не меняется. Смотри на три вывода: 10, 5, снова 10.
package main

import "fmt"

func main() {
	x := 10
	if x > 5 {
		fmt.Println(x)
		x := 5
		// новая переменная внутри блока if; внешняя x к ней отношения не имеет
		fmt.Println(x)
	}
	fmt.Println(x)
	// снова 10 — затенение закончилось вместе с блоком
}
