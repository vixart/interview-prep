// Затенение при множественном присваивании.
// `x, y := 5, 20` внутри if создает НОВУЮ x (потому что y новая, и := объявляет обе),
// поэтому внешняя x остается равной 10. Частый источник «почему значение не изменилось».
package main

import "fmt"

func main() {
	x := 10
	if x > 5 {
		x, y := 5, 20
		// := объявляет ОБЕ переменные, потому что y новая → внутренняя x затеняет внешнюю
		fmt.Println(x, y)
	}
	fmt.Println(x)
	// внешняя x нетронута: 10
}
