// Срез, сделанный из массива (x[:2]), смотрит в память массива:
// изменение x[0] видно через срез y. Массив → срез — это всегда общая память.
package main

import (
	"fmt"
)

func main() {
	x := [4]int{5, 6, 7, 8}
	y := x[:2]
	// срез, сделанный из массива, смотрит в память массива
	z := x[2:]
	x[0] = 10
	// меняем МАССИВ...
	fmt.Println("x:", x)
	fmt.Println("y:", y)
	// ...и это видно через срез y
	fmt.Println("z:", z)
}
