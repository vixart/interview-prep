// Подсрезы разделяют память с исходным срезом:
// запись в x, y и z изменяет одни и те же ячейки. Копии не происходит.
package main

import "fmt"

func main() {
	x := []string{"a", "b", "c", "d"}
	y := x[:2]
	// y и z — окна в тот же массив, копии нет
	z := x[1:]
	x[1] = "y"
	y[0] = "x"
	// запись через y видна в x
	z[1] = "z"
	// z начинается с x[1], поэтому z[1] — это x[2]
	fmt.Println("x:", x)
	fmt.Println("y:", y)
	fmt.Println("z:", z)
}
