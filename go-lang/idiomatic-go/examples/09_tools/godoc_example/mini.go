// Package mini демонстрирует минимальный набор правил Go Doc.
//
// # Overview
//
// Комментарий документации — это блок //, стоящий вплотную к объявлению
// и начинающийся с имени объявления. Пакетный комментарий пишут перед
// package и начинают со слов "Package имя".
//
// Форматирование:
//   - "# Заголовок" — заголовок раздела;
//   - строки с отступом — блок кода;
//   - список — строки, начинающиеся с "  - ";
//   - [fmt] — ссылка на пакет, [Add] — ссылка на символ;
//   - голый URL становится ссылкой: https://pkg.go.dev
//
// Смотреть документацию: go doc ./09_tools/godoc_example
// или локальный сайт: go install golang.org/x/pkgsite/cmd/pkgsite@latest && pkgsite
package mini

// Version содержит версию пакета.
const Version = "v0.1.0"

// Add складывает два целых числа.
//
// Пример:
//
//	result := Add(2, 3)
//
// Может использоваться совместно с пакетом [fmt].
func Add(a, b int) int {
	return a + b
}

// unexported не попадет в go doc: имя начинается со строчной буквы.
func unexported() {}
