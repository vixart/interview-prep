// Порядок обхода map случайный: три прогона по одной и той же map дают разный порядок.
// Это защита от Hash DoS. Если нужен стабильный порядок — сортируй ключи.
package main

import "fmt"

func main() {
	m := map[string]int{
		"a": 1,
		"c": 3,
		"b": 2,
	}

	for i := 0; i < 3; i++ {
		fmt.Println("Loop", i)
		for k, v := range m {
			// порядок ключей меняется от прогона к прогону — на него нельзя опираться
			fmt.Println(k, v)
		}
	}
}
