// Ловушка замыкания: := внутри анонимной функции создает НОВУЮ переменную,
// а не меняет внешнюю. Сравни с примером closure, где стоит a = 30.
package main

import "fmt"

func main() {
	a := 20
	f := func() {
		fmt.Println(a)
		a := 30
		// := вместо = → внутри замыкания появилась своя a, внешняя не тронута
		fmt.Println(a)
	}
	f()
	fmt.Println(a)
	// печатает 20: изменения из замыкания не видно
}
