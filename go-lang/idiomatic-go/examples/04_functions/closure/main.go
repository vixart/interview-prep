// Замыкание видит и ИЗМЕНЯЕТ переменную внешней функции:
// после вызова f() внешняя a равна 30. Ловушка рядом: `a := 30` вместо `a = 30`
// создало бы новую переменную внутри замыкания.
package main

import "fmt"

func main() {
	a := 20
	// переменная внешней функции
	f := func() {
		fmt.Println(a)
		a = 30
		// замыкание МЕНЯЕТ внешнюю a (было бы a := 30 — создалась бы новая, внутренняя)
	}
	f()
	fmt.Println(a)
	// печатает 30: изменение видно снаружи
}
