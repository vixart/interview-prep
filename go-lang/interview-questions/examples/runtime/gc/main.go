// Как устроен сборщик мусора в Go.
//
// Алгоритм: конкурентный трехцветный mark-and-sweep с барьером записи.
// Не перемещающий (объекты не двигаются, поэтому указатели стабильны),
// не поколенческий, настроен на МИНИМАЛЬНУЮ ПАУЗУ, а не на пропускную способность.
//
// Цикл:
//  1. sweep termination — короткий STW, включается барьер записи;
//  2. mark — конкурентно с программой обходим граф достижимости от корней
//     (стеки горутин, глобальные переменные); барьер записи ловит указатели,
//     которые программа меняет прямо во время обхода;
//  3. mark termination — второй короткий STW, выключаем барьер;
//  4. sweep — освобождение конкурентно, по мере аллокаций.
//
// Пауз мира две, обе микросекундные (цель < 500 мкс). Основная стоимость GC —
// не паузы, а CPU: примерно 25% времени (GOGC-ассист), которые он отнимает у программы.
//
// Настройки:
//
//	GOGC=100 (по умолчанию) — следующая сборка, когда куча вырастет вдвое
//	                          относительно живых данных после прошлой сборки;
//	GOGC=off                — выключить (только с GOMEMLIMIT!);
//	GOMEMLIMIT=512MiB       — мягкий лимит всей памяти рантайма: при приближении
//	                          GC начинает работать чаще, даже если GOGC далеко.
//
// Посмотреть вживую:
//
//	GODEBUG=gctrace=1 go run ./runtime/gc
package main

import (
	"fmt"
	"runtime"
	"runtime/debug"
)

type node struct {
	data [1024]byte
	next *node
}

func allocate(n int) *node {
	var head *node
	for i := 0; i < n; i++ {
		head = &node{next: head} // список из n объектов по ~1 КБ
	}
	return head
}

var prevGC uint32
var prevPause uint64

// stats печатает состояние кучи и то, сколько циклов GC прошло С ПРОШЛОГО вызова.
func stats(label string) {
	var ms runtime.MemStats
	runtime.ReadMemStats(&ms)
	fmt.Printf("%-24s куча %5.1f МБ | циклов GC: %3d | паузы: %6.3f мс\n",
		label,
		float64(ms.HeapAlloc)/1024/1024,
		ms.NumGC-prevGC,
		float64(ms.PauseTotalNs-prevPause)/1e6)
	prevGC, prevPause = ms.NumGC, ms.PauseTotalNs
}

func main() {
	stats("старт")

	// 1. Мусор: список создается и тут же теряется — GC его соберет.
	for i := 0; i < 20; i++ {
		_ = allocate(10_000) // ~10 МБ мусора за итерацию
	}
	stats("после 200 МБ мусора")

	// 2. Живые данные: пока на них есть ссылка, GC ничего не освободит.
	live := allocate(50_000)
	runtime.GC()
	stats("50k живых объектов")
	runtime.KeepAlive(live)
	// KeepAlive обязателен: иначе компилятор сочтет live мертвым уже здесь,
	// GC соберет список, и в выводе не будет видно разницы

	// 3. Ссылку убрали → объекты стали мусором → следующий цикл их соберет.
	live = nil
	runtime.GC()
	stats("после live = nil")
	_ = live

	// 4. Ручка GOGC: чем больше значение, тем реже сборки и больше памяти.
	old := debug.SetGCPercent(400) // как GOGC=400
	for i := 0; i < 20; i++ {
		_ = allocate(10_000)
	}
	stats("те же 200 МБ, GOGC=400")
	debug.SetGCPercent(old)

	// 5. GOMEMLIMIT: мягкий потолок, GC начнет частить, не дожидаясь GOGC.
	debug.SetMemoryLimit(64 << 20) // 64 МБ
	for i := 0; i < 20; i++ {
		_ = allocate(10_000)
	}
	stats("с GOMEMLIMIT=64МБ")
	debug.SetMemoryLimit(1<<63 - 1) // снять лимит

	fmt.Println("\nЧастые вопросы:")
	fmt.Println("- Что такое корни? Стеки всех горутин + глобальные переменные.")
	fmt.Println("- Что такое барьер записи? Хук на запись указателя во время фазы mark,")
	fmt.Println("  без него конкурентная пометка теряла бы объекты.")
	fmt.Println("- Почему нет compaction? GC не перемещающий: адреса стабильны,")
	fmt.Println("  зато возможна фрагментация — лечится размерными классами аллокатора.")
	fmt.Println("- Финализаторы (runtime.SetFinalizer) есть, но их не используют:")
	fmt.Println("  порядок и время вызова не гарантированы. Освобождай ресурсы через defer/Close.")
	fmt.Println("- Как уменьшить давление на GC? Меньше указателей, преаллокация,")
	fmt.Println("  переиспользование буферов, значения вместо указателей в срезах.")
}
