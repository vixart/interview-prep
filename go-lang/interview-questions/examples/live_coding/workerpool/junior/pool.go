// Junior-версия воркер-пула (~40 строк) — то, что пишут на доске за пять минут.
// В демо работает, но в прод нести нельзя: ниже пять помеченных багов.
//
// Как работает: New стартует N воркеров, каждый читает общий канал задач
// через for-range; Close закрывает канал, воркеры доедают буфер и выходят,
// wg.Wait дожидается всех.
package main

import "sync"

type WorkerPool struct {
	tasks  chan func()
	wg     sync.WaitGroup
	mu     sync.Mutex
	closed bool // БАГ #5: флаг рядом с каналом — две модели синхронизации сразу
}

func New(workers int) *WorkerPool {
	p := &WorkerPool{
		// БАГ #1: магическое число. Размер очереди — это политика (сколько
		// задач готовы держать в памяти), она обязана быть параметром.
		tasks: make(chan func(), 100),
	}
	for range workers {
		p.wg.Add(1) // Add до go — то немногое, что здесь сделано правильно
		go p.worker()
	}
	return p
}

func (p *WorkerPool) worker() {
	defer p.wg.Done()
	// for-range по каналу завершится сам, когда канал закроют и буфер опустеет.
	for task := range p.tasks {
		// БАГ #2: нет recover. Паника в одной задаче убивает воркера — пул
		// молча деградирует с N воркеров до нуля, и заметить это нечем:
		// wg.Done в defer сработает, Close вернется как ни в чем не бывало.
		task()
	}
}

func (p *WorkerPool) AddTask(f func()) {
	// БАГ #3 (TOCTOU): проверка и использование разнесены. Между Unlock и
	// send в канал успевает пройти Close → "panic: send on closed channel".
	// Отдельно: если буфер полон, send блокируется ЗДЕСЬ, и параллельный
	// Close закрывает канал прямо под заблокированным отправителем — та же
	// паника, но воспроизводится детерминированно (см. pool_test.go).
	p.mu.Lock()
	if p.closed {
		p.mu.Unlock()
		return // БАГ #4: молча теряем задачу, вызывающий об отказе не узнает
	}
	p.mu.Unlock()

	p.tasks <- f
}

func (p *WorkerPool) Close() {
	p.mu.Lock()
	p.closed = true
	// Закрытие канала задач — корень зла: пока у AddTask есть право писать
	// в этот канал, любое закрытие потенциально паникует. В middle-версии
	// tasks не закрывается НИКОГДА, а воркеры выходят по сигнальным каналам.
	close(p.tasks)
	p.mu.Unlock()
	p.wg.Wait()
	// БАГ #5 (продолжение): нет контекста и дедлайна. Close висит столько,
	// сколько выполняется самая долгая задача, прервать нечем: задача —
	// это func() без параметров, про отмену она ничего не знает.
}
