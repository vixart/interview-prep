// Чем отличаются буферизованный и небуферизованный каналы.
//
// Небуферизованный (make(chan T)) — это РАНДЕВУ: отправитель и получатель
// встречаются в одной точке. Отправка завершается только тогда, когда кто-то
// принял значение, поэтому такой канал дает гарантию «сообщение получено»
// и синхронизирует две горутины.
//
// Буферизованный (make(chan T, n)) — это ОЧЕРЕДЬ на n элементов. Отправка
// завершается сразу, пока есть место; отправитель не знает, прочитали ли его.
// Синхронизации нет, зато нет и лишних переключений.
package main

import (
	"fmt"
	"sync"
	"time"
)

func unbuffered() {
	ch := make(chan int) // len 0, cap 0
	var wg sync.WaitGroup
	wg.Add(1)

	go func() {
		defer wg.Done()
		time.Sleep(50 * time.Millisecond)
		v := <-ch // отправитель ждал именно этой строки
		fmt.Println("  получено:", v)
	}()

	start := time.Now()
	ch <- 1 // блокируется, пока получатель не заберет значение
	fmt.Printf("  отправка вернулась через %v — значит значение уже приняли\n",
		time.Since(start).Round(10*time.Millisecond))
	wg.Wait()
}

func buffered() {
	ch := make(chan int, 3) // len 0, cap 3

	start := time.Now()
	ch <- 1
	ch <- 2
	ch <- 3 // три отправки мгновенные: в буфере есть место
	fmt.Printf("  три отправки заняли %v, len=%d cap=%d — читателя нет вообще\n",
		time.Since(start).Round(time.Millisecond), len(ch), cap(ch))

	// Четвертая отправка заблокировалась бы: буфер полон.
	select {
	case ch <- 4:
		fmt.Println("  влезло четвертое")
	default:
		fmt.Println("  четвертое не влезло: буфер полон (select с default это ловит)")
	}

	fmt.Println("  читаем:", <-ch, <-ch, <-ch)
}

func closedChannel() {
	ch := make(chan int, 2)
	ch <- 1
	close(ch)

	v, ok := <-ch // из закрытого канала сначала вычитывается буфер
	fmt.Printf("  из буфера: v=%d ok=%v\n", v, ok)
	v, ok = <-ch // потом — нулевое значение и ok == false
	fmt.Printf("  после исчерпания: v=%d ok=%v\n", v, ok)

	// Что паникует, а что нет:
	// - чтение из закрытого канала: ок, всегда;
	// - запись в закрытый: panic "send on closed channel";
	// - повторный close: panic "close of closed channel";
	// - close(nil-канала): panic;
	// - чтение/запись nil-канала: блокировка НАВСЕГДА (используется, чтобы
	//   отключить ветвь select).
}

func main() {
	fmt.Println("1. Небуферизованный — рандеву:")
	unbuffered()

	fmt.Println("\n2. Буферизованный — очередь:")
	buffered()

	fmt.Println("\n3. Закрытый канал:")
	closedChannel()

	fmt.Println("\nЧто выбирать:")
	fmt.Println("- по умолчанию небуферизованный: он честно показывает, что система")
	fmt.Println("  не успевает, и дает happens-before между отправителем и получателем;")
	fmt.Println("- буфер оправдан, когда: известно точное число результатов;")
	fmt.Println("  нужен семафор (буфер = лимит); нужно развязать всплески нагрузки;")
	fmt.Println("  нужно, чтобы горутина отдала результат и завершилась (буфер 1 при таймауте);")
	fmt.Println("- большой буфер не ускоряет систему, он лишь прячет проблему")
	fmt.Println("  и увеличивает задержку и потребление памяти.")
}
