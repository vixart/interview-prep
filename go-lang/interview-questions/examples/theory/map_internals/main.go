// Словари: что спрашивают про map.
//
// Устройство: хеш-таблица из бакетов, в каждом до 8 пар ключ-значение.
// Ключ хешируется, младшие биты выбирают бакет, старшие 8 бит (tophash)
// быстро отсеивают несовпадения внутри бакета. Переполнение — цепочка
// overflow-бакетов. При заполнении ~6.5 элементов на бакет таблица растет
// вдвое, и перехеширование идет ИНКРЕМЕНТАЛЬНО (по 1-2 бакета на операцию).
//
// Следствия, о которых спрашивают:
//   - порядок обхода случайный (рандомизирован специально, защита от Hash DoS);
//   - адрес элемента взять нельзя: при росте таблицы элементы переезжают;
//   - map не потокобезопасна: конкурентная запись = fatal error, не паника;
//   - map всегда передается по ссылке на общую структуру (внутри указатель);
//   - удаление не уменьшает таблицу: память под бакеты остается за map.
package main

import (
	"fmt"
	"sync"
)

type user struct {
	Name string
	Hits int
}

func main() {
	// 1. Нельзя взять адрес элемента и нельзя менять поле структуры на месте.
	m := map[string]user{"bob": {Name: "Bob"}}
	// m["bob"].Hits++        // ошибка компиляции: cannot assign
	// p := &m["bob"]         // ошибка компиляции: cannot take address
	u := m["bob"] // читаем копию...
	u.Hits++
	m["bob"] = u // ...меняем и кладем обратно
	fmt.Println("1. через копию:", m["bob"])

	// Поэтому для изменяемых значений держат УКАЗАТЕЛИ:
	mp := map[string]*user{"bob": {Name: "Bob"}}
	mp["bob"].Hits++ // так можно: меняем объект по указателю, а не элемент map
	fmt.Println("   через указатель:", *mp["bob"])

	// 2. Нулевая map: читать можно, писать — паника.
	var nilMap map[string]int
	fmt.Println("2. чтение из nil-map:", nilMap["нет такого"], "len:", len(nilMap))
	// nilMap["a"] = 1 // panic: assignment to entry in nil map

	// 3. Предварительный размер экономит перехеширования.
	sized := make(map[int]int, 10_000) // одна аллокация под нужное число бакетов
	for i := 0; i < 10_000; i++ {
		sized[i] = i
	}
	fmt.Println("3. заполнено с преаллокацией:", len(sized))

	// 4. delete не отдает память обратно; чтобы реально освободить —
	// пересоздать map (или clear + смириться с тем, что бакеты остались).
	for i := 0; i < 10_000; i++ {
		delete(sized, i)
	}
	fmt.Println("4. после delete всех ключей len:", len(sized), "— но бакеты остались за map")
	clear(sized) // Go 1.21+: очистить, не пересоздавая

	// 5. Конкурентный доступ. Запись из нескольких горутин — fatal error
	//    "concurrent map writes", его НЕЛЬЗЯ поймать через recover.
	//    Демонстрация под тегом: go run -tags mapfatal ./theory/map_internals
	concurrentDemo()

	// Правильно: мьютекс поверх обычной map...
	safe := struct {
		mu sync.RWMutex
		m  map[string]int
	}{m: map[string]int{}}

	var wg sync.WaitGroup
	wg.Add(100)
	for i := 0; i < 100; i++ {
		go func(i int) {
			defer wg.Done()
			safe.mu.Lock()
			safe.m[fmt.Sprint(i%10)]++
			safe.mu.Unlock()
		}(i)
	}
	wg.Wait()
	fmt.Println("5. под RWMutex, ключей:", len(safe.m))

	// ...или sync.Map — но только для двух сценариев из документации:
	// (1) ключ пишется один раз, читается много; (2) горутины работают
	// с непересекающимися наборами ключей. В остальных случаях
	// обычная map + RWMutex быстрее и понятнее.
	var sm sync.Map
	sm.Store("a", 1)
	v, ok := sm.Load("a")
	fmt.Println("   sync.Map:", v, ok)
}
