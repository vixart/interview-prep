package main

import (
	"net/http" // пакет для HTTP-клиента и HTTP-сервера
	"time"     // пакет для работы со временем (таймауты)
)

// HelloHandler — наш обработчик HTTP-запросов.
// Пустая структура, которая будет реализовывать интерфейс http.Handler.
type HelloHandler struct{}

// ServeHTTP — метод, который должен реализовать любой http.Handler.
// Если тип имеет этот метод, он автоматически реализует интерфейс http.Handler.
func (hh HelloHandler) ServeHTTP(w http.ResponseWriter, r *http.Request) {

	// w — интерфейс ResponseWriter, через него формируется HTTP-ответ
	// r — объект запроса (URL, заголовки, метод, тело и т.д.)

	// Write записывает тело HTTP-ответа клиенту.
	// Если WriteHeader не был вызван ранее, автоматически отправляется код 200 OK.
	w.Write([]byte("Hello!\n"))
}

func main() {

	// Создаем экземпляр HTTP-сервера.
	// http.Server — структура, управляющая приемом HTTP-запросов.
	s := http.Server{

		// Addr — адрес и порт, на котором сервер будет слушать входящие соединения.
		// ":8080" означает:
		// слушать на всех интерфейсах (0.0.0.0) на порту 8080.
		Addr: ":8080",

		// ReadTimeout — максимальное время чтения запроса от клиента.
		// Защищает от клиентов, которые отправляют запрос слишком медленно.
		ReadTimeout: 30 * time.Second,

		// WriteTimeout — максимальное время отправки ответа клиенту.
		// Если ответ не отправлен за это время — соединение закрывается.
		WriteTimeout: 90 * time.Second,

		// IdleTimeout — время ожидания следующего запроса
		// при keep-alive соединении.
		IdleTimeout: 120 * time.Second,

		// Handler — обработчик HTTP-запросов.
		// Здесь мы передаем экземпляр HelloHandler,
		// который будет обрабатывать ВСЕ запросы.
		Handler: HelloHandler{},
	}

	// Запускаем HTTP-сервер.
	// ListenAndServe:
	// 1. открывает TCP-сокет
	// 2. начинает слушать указанный порт
	// 3. принимает HTTP-запросы
	// 4. передает их обработчику Handler
	err := s.ListenAndServe()

	// ListenAndServe возвращает ошибку только при остановке сервера
	// или при возникновении проблем.
	if err != nil {

		// http.ErrServerClosed — нормальная ошибка при штатном закрытии сервера.
		// В этом случае паниковать не нужно.
		if err != http.ErrServerClosed {

			// Если ошибка другая — это проблема, поэтому падаем.
			panic(err)
		}
	}
}
